"""The user guide says what the software does, and nothing in it points nowhere.

Its reference tables are generated by ``scripts/guide_tables.py`` from the
parser and the metadata fields, and these fail when either has moved on without
the guide. Every link and picture is checked to exist, and every page is
reachable from the user guide. The README's links are absolute, being PyPI's
description too.
"""
from __future__ import annotations

import re
from pathlib import Path

import guide_tables
import pytest

GUIDES = guide_tables.GUIDES
REPOSITORY = guide_tables.REPOSITORY

#: A Markdown link or picture: ``[text](target)`` or ``![text](target)``.
LINK = re.compile(r"!?\[[^\]]*\]\(([^)\s]+)\)")


def _block(name: str) -> str:
    """Return the text between a page's markers for the table *name*."""
    text = guide_tables.PAGES[name].read_text(encoding="utf-8")
    return guide_tables._BLOCK.search(text[text.index(f"<!-- generated: {name} -->"):])["body"]


def _regenerate_hint(name: str) -> str:
    return f"the {name} table is out of date: run `uv run python scripts/guide_tables.py`"


def test_the_command_table_is_every_command_as_its_help_gives_it():
    assert _block("commands").strip() == guide_tables.commands_markdown().strip(), (
        _regenerate_hint("commands")
    )


def test_the_field_table_is_every_field_add_data_offers():
    assert _block("fields").strip() == guide_tables.fields_markdown().strip(), (
        _regenerate_hint("fields")
    )


def test_a_generated_block_is_replaced_and_nothing_around_it():
    text = "before\n<!-- generated: keys -->\nold\n<!-- end generated -->\nafter\n"

    replaced = guide_tables.replace_generated(text, "keys", "new")

    assert replaced == "before\n<!-- generated: keys -->\n\nnew\n\n<!-- end generated -->\nafter\n"


def test_a_page_without_the_block_is_refused():
    with pytest.raises(ValueError, match="commands"):
        guide_tables.replace_generated("no markers here\n", "commands", "table")


@pytest.mark.parametrize("page", sorted(GUIDES.glob("*.md")), ids=lambda page: page.name)
def test_every_link_and_picture_in_the_guide_is_there(page: Path):
    missing = []
    for target in LINK.findall(page.read_text(encoding="utf-8")):
        if re.match(r"[a-z]+:", target):
            continue
        path = target.split("#")[0]
        if path and not (page.parent / path).exists():
            missing.append(target)

    assert not missing, f"{page.name} points at what is not there: {missing}"


#: Where the README's links into this repository point: PyPI shows the README as
#: a release's description, resolves no relative link, and keeps it unchanged.
REPOSITORY_ON_MAIN = (
    "https://github.com/Casper-rfi/AM_segmentation_manager/blob/main/",
    "https://raw.githubusercontent.com/Casper-rfi/AM_segmentation_manager/main/",
)


def test_every_link_in_the_readme_is_absolute_and_what_it_names_is_there():
    relative, missing = [], []
    for target in LINK.findall((REPOSITORY / "README.md").read_text(encoding="utf-8")):
        if not re.match(r"[a-z]+:", target):
            relative.append(target)
        elif target.startswith(REPOSITORY_ON_MAIN):
            path = target.split("/main/", 1)[1].split("#")[0]
            if not (REPOSITORY / path).exists():
                missing.append(target)

    assert not relative, f"PyPI cannot follow these README links: {relative}"
    assert not missing, f"the README points at what is not there: {missing}"


def test_every_page_is_linked_from_the_user_guide():
    guide = (GUIDES / "user_guide.md").read_text(encoding="utf-8")
    linked = {target.split("#")[0] for target in LINK.findall(guide)}

    unlinked = [page.name for page in GUIDES.glob("*.md") if page.name != "user_guide.md"
                and page.name not in linked]

    assert not unlinked, f"pages nobody can find from guides/user_guide.md: {unlinked}"


def test_every_picture_is_shown_somewhere():
    shown = {
        Path(target).name
        for page in [*GUIDES.glob("*.md"), REPOSITORY / "README.md"]
        for target in LINK.findall(page.read_text(encoding="utf-8"))
    }

    unshown = sorted(image.name for image in (GUIDES / "images").glob("*.png")
                     if image.name not in shown)

    assert not unshown, f"pictures no page shows: {unshown}"
